static inline uintptr_t get_cycle_count() {
    uintptr_t cycle;
    __asm__ volatile ("csrr %0, cycle" : "=r" (cycle));
    return cycle;
}

uint64_t gccs(void)
{
    uint64_t res;
    uint64_t result;
    __asm__ volatile ("csrr %0, cycle" : "=r" (res));

    asm volatile (
		"add %0, %1, x0"
		: "=r" (result)
		: "r" (res)
	);  

    return result;
}

void DelayMs(int d)
{
    uintptr_t t_start;

    t_start = get_cycle_count();
    while(get_cycle_count() - t_start < (d * MS_CYCLES)) {}
}

uint8_t ReadU8(void)
{
    uint8_t rxb = 0xFF;

    while(1)
    {
        if(read_serial(&rxb)==1)
        {
            return rxb;
        }
        start = get_cycle_count();
        while(get_cycle_count() - start < 100) {}
    }
    
    return 0xFF;
}

uint8_t GetNibble(char c)
{
    switch(c)
    {
        case '0': return  0;
        case '1': return  1;
        case '2': return  2;
        case '3': return  3;
        case '4': return  4;
        case '5': return  5;
        case '6': return  6;
        case '7': return  7;
        case '8': return  8;
        case '9': return  9;
        case 'A': 
        case 'a': return 10;
        case 'B': 
        case 'b': return 11;
        case 'C': 
        case 'c': return 12;
        case 'D': 
        case 'd': return 13;
        case 'E': 
        case 'e': return 14;
        case 'F': 
        case 'f': return 15;
        default:  return  0;
    }
}

